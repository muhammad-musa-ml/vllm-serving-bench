"""Fill the results section of README.md from results/summary.json and results/server/<arm>/facts.json.

    python scripts/render_readme_results.py [--results results] [--readme README.md]

Everything between the lines `<!-- results:start -->` and `<!-- results:end -->` is replaced; no figure in
that block is typed by hand. Running it twice gives the same file.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from servebench.report import dig, ms, pct  # noqa: E402
from servebench.stats import fmt_range  # noqa: E402

START = "<!-- results:start -->"
END = "<!-- results:end -->"
ARMS = ["fp16", "awq", "gptq"]


def cell(summary, digits=1, convert=None):
    if summary is None:
        return "-"
    if convert:
        summary = convert(summary)
    return fmt_range(summary, digits)


def facts_for(results, arm):
    path = results / "server" / arm / "facts.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def sat_closed(sat):
    if sat["concurrency"] is None:
        return f"not reached by 16 workers (peak {sat['peak_tok_s']:.0f} tok/s)"
    return (f"{sat['concurrency']} workers ({sat['tok_s_at_knee']:.0f} tok/s; "
            f"{sat['tok_s_at_next']:.0f} at the next level)")


def sat_open(sat):
    return f"{sat['rate']:g} req/s offered" if sat.get("rate") else "not reached in the tested rates"


def render(summary, results):
    arms = [a for a in ARMS if a in summary["arms"] and "closed" in summary["arms"][a]]
    out = [START, "", "<!-- generated by scripts/render_readme_results.py; do not edit by hand -->", ""]
    n_runs = {a: summary["arms"][a]["n_runs"] for a in arms}
    out += [f"Median of {min(n_runs.values())} runs with the range (min-max) in brackets, from "
            "[`results/summary.json`](results/summary.json). The full tables, with pooled percentiles, "
            "are in [`results/summary.md`](results/summary.md).", ""]

    out += ["### At a glance", "", "| | " + " | ".join(arms) + " |", "|---|" + "---|" * len(arms)]

    def row(label, fn):
        out.append(f"| {label} | " + " | ".join(fn(a) for a in arms) + " |")

    def fact(a, key, fmt):
        v = facts_for(results, a).get(key)
        return "-" if v is None else fmt.format(v)

    row("weights in GPU memory, GiB", lambda a: fact(a, "model_loading_gib", "{:.2f}"))
    row("KV cache that fits, tokens", lambda a: fact(a, "kv_cache_tokens", "{:,}"))
    row("output tokens/s, 1 worker", lambda a: cell(dig(summary, "arms", a, "closed", "1", "out_tok_s")))
    row("output tokens/s, 16 workers", lambda a: cell(dig(summary, "arms", a, "closed", "16", "out_tok_s")))
    row("end-to-end p50 for 128 tokens, 1 worker, s",
        lambda a: cell(dig(summary, "arms", a, "closed", "1", "e2e_p50_s"), 2))
    row("end-to-end p50, 16 workers, s",
        lambda a: cell(dig(summary, "arms", a, "closed", "16", "e2e_p50_s"), 2))
    row("time to first token p50, 16 workers, ms",
        lambda a: cell(dig(summary, "arms", a, "closed", "16", "ttft_p50_s"), 0, ms))
    row("closed-loop saturation", lambda a: sat_closed(summary["arms"][a]["saturation"]["closed"]))
    row("open-loop saturation", lambda a: sat_open(summary["arms"][a]["saturation"]["open"]))
    qarms = [a for a in arms if "quality" in summary["arms"][a]]
    if qarms:
        for setname, label in (("mmlu-subset", "MMLU subset accuracy, 285 questions, %"),
                               ("synthetic-tasks", "synthetic tasks accuracy, 120 items, %")):
            row(label, lambda a, s=setname: cell(dig(summary, "arms", a, "quality", "by_set", s), 1, pct))
    out.append("")

    out += ["### Closed loop", ""]
    for a in arms:
        out += [f"**{a}**", "",
                "| workers | output tok/s | req/s | TTFT p50 ms | TTFT p95 ms | e2e p50 s | e2e p95 s | "
                "e2e p99 s | GPU memory peak MiB |", "|---|---|---|---|---|---|---|---|---|"]
        for c, m in summary["arms"][a]["closed"].items():
            out.append(f"| {c} | {cell(m['out_tok_s'])} | {cell(m['req_s'], 2)} | "
                       f"{cell(m['ttft_p50_s'], 0, ms)} | {cell(m['ttft_p95_s'], 0, ms)} | "
                       f"{cell(m['e2e_p50_s'], 2)} | {cell(m['e2e_p95_s'], 2)} | {cell(m['e2e_p99_s'], 2)} | "
                       f"{cell(m['gpu_mem_peak_mib'], 0)} |")
        out.append("")
    out += ["![throughput](results/plots/throughput-vs-concurrency.png)", "",
            "![latency](results/plots/latency-vs-concurrency.png)", ""]

    out += ["### Open loop", ""]
    for a in arms:
        out += [f"**{a}**", "",
                "| offered req/s | arrivals per second (realized) | completed req/s | completed % | "
                "e2e p50 s | e2e p95 s | e2e p99 s | unfinished |", "|---|---|---|---|---|---|---|---|"]
        for r, m in summary["arms"][a]["open"].items():
            out.append(f"| {float(r):g} | {cell(m['realized_rate'], 2)} | {cell(m['req_s_overall'], 2)} | "
                       f"{cell(m['completion_ratio'], 0, pct)} | {cell(m['e2e_p50_s'], 2)} | "
                       f"{cell(m['e2e_p95_s'], 2)} | {cell(m['e2e_p99_s'], 2)} | "
                       f"{cell(m['n_unfinished'], 0)} |")
        out.append("")
    out += ["![open loop](results/plots/open-loop.png)", ""]

    if qarms:
        qp = summary.get("quality_pairs", {})
        out += ["### Quality", "",
                "| arm | all 405 | mmlu-subset | synthetic-tasks |", "|---|---|---|---|"]
        for a in qarms:
            q = summary["arms"][a]["quality"]
            out.append(f"| {a} | {cell(q['all'], 1, pct)} | {cell(q['by_set'].get('mmlu-subset'), 1, pct)} | "
                       f"{cell(q['by_set'].get('synthetic-tasks'), 1, pct)} |")
        out.append("")
        if qp.get("vs_fp16"):
            out += ["Paired against fp16, on the questions each arm got right in most of its runs "
                    "(exact McNemar test on the questions where they differ):", "",
                    "| arm | both right | only fp16 right | only this arm right | both wrong | p |",
                    "|---|---|---|---|---|---|"]
            for a, p in qp["vs_fp16"].items():
                out.append(f"| {a} | {p['both_right']} | {p['only_baseline_right']} | "
                           f"{p['only_arm_right']} | {p['both_wrong']} | {p['mcnemar_p']:.3f} |")
            out.append("")
        if qp.get("instability_items"):
            out.append("Questions whose result changed between runs of the same arm: "
                       + ", ".join(f"{a} {n}" for a, n in qp["instability_items"].items()) + ".")
            out.append("")
    out.append(END)
    return "\n".join(out)


def replace_block(readme_text, block):
    if START not in readme_text or END not in readme_text:
        raise SystemExit(f"README has no {START} / {END} markers")
    head, rest = readme_text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--readme", default="README.md")
    args = ap.parse_args()
    results = ROOT / args.results
    summary = json.loads((results / "summary.json").read_text(encoding="utf-8"))
    readme = ROOT / args.readme
    new = replace_block(readme.read_text(encoding="utf-8"), render(summary, results))
    readme.write_text(new, encoding="utf-8", newline="\n")
    print(f"updated {readme}")


if __name__ == "__main__":
    main()
